from datetime import datetime


def detect_sun_sign(birth_date: str) -> str:
    date = datetime.strptime(birth_date, "%Y-%m-%d")
    month = date.month
    day = date.day

    ranges = [
        ((1, 20), "Козерог", "Собранность, амбиция и ориентация на долгий результат."),
        ((2, 19), "Водолей", "Независимость, оригинальность мышления и тяга к свободе."),
        ((3, 21), "Рыбы", "Интуитивность, чувствительность и богатый внутренний мир."),
        ((4, 20), "Овен", "Инициативность, энергия и стремление действовать быстро."),
        ((5, 21), "Телец", "Устойчивость, чувственность и любовь к надёжности."),
        ((6, 21), "Близнецы", "Любознательность, общительность и гибкость мышления."),
        ((7, 23), "Рак", "Эмоциональная глубина, забота и сильная связь с близкими."),
        ((8, 23), "Лев", "Яркость, творческая сила и потребность сиять."),
        ((9, 23), "Дева", "Внимание к деталям, практичность и стремление улучшать."),
        ((10, 23), "Весы", "Дипломатичность, чувство гармонии и потребность в балансе."),
        ((11, 22), "Скорпион", "Интенсивность, внутренняя сила и стремление к трансформации."),
        ((12, 22), "Стрелец", "Оптимизм, масштаб мышления и тяга к росту."),
        ((12, 32), "Козерог", "Собранность, амбиция и ориентация на долгий результат."),
    ]

    sign = "Козерог"
    trait = "Собранность, амбиция и ориентация на долгий результат."

    for (end_month, end_day), current_sign, current_trait in ranges:
        if (month, day) < (end_month, end_day):
            sign = current_sign
            trait = current_trait
            break

    return sign, trait


def build_natal_summary(name: str, birth_date: str, birth_place: str) -> tuple[str, str, str]:
    sign, trait = detect_sun_sign(birth_date)
    summary = f"{name}: базовый натальный портрет — знак Солнца {sign}."
    interpretation = (
        f"Для профиля {name}, рождённого в {birth_place}, MVP-интерпретация показывает знак Солнца {sign}. "
        f"Ключевой акцент: {trait} Это пока стартовая rule-based версия, которую позже можно расширить "
        f"домами, аспектами, асцендентом и AI-объяснениями простым языком."
    )
    return summary, sign, interpretation
